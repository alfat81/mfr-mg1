export type StageStatus = "upcoming" | "registration" | "completed" | "live";

export interface Stage {
  id: number;
  date: string;
  dateRange: string; // short label
  fullDate: string; // ISO-ish — official competition start (used for countdown)
  endDate?: string; // ISO-ish — competition end (used to mark "completed" / "live")
  city: string;
  region: string;
  venue: string;
  organizer: string;
  phone?: string;
  phone2?: string;
  email?: string;
  protocol: string;
  track: string;
  status: StageStatus;
  externalResultsUrl?: string;
  externalStageUrl?: string;
  coordinates?: { lat: number; lng: number };
}

/**
 * Возвращает статус этапа на основе текущей даты:
 * - completed — если сегодня уже позже даты окончания
 * - live — если сегодня в диапазоне [start, end]
 * - registration — если до старта осталось <= 30 дней (открыта регистрация)
 * - upcoming — иначе
 */
export function resolveStageStatus(
  stage: Pick<Stage, "fullDate" | "endDate">,
  now: Date = new Date(),
): Exclude<StageStatus, undefined> {
  const start = new Date(stage.fullDate).getTime();
  const end = stage.endDate ? new Date(stage.endDate).getTime() : start + 86400000;
  const nowMs = now.getTime();
  if (nowMs > end) return "completed";
  if (nowMs >= start && nowMs <= end) return "live";
  const daysToStart = (start - nowMs) / 86400000;
  return daysToStart <= 30 ? "registration" : "upcoming";
}

/**
 * Находит следующий предстоящий этап (status !== "completed").
 * Возвращает null, если сезон завершён.
 */
export function getNextStage(stages: Stage[] = STAGES, now: Date = new Date()): Stage | null {
  const upcoming = stages
    .filter((s) => resolveStageStatus(s, now) !== "completed")
    .sort((a, b) => new Date(a.fullDate).getTime() - new Date(b.fullDate).getTime());
  return upcoming[0] ?? null;
}

/**
 * Возвращает список завершённых этапов (по убыванию даты).
 */
export function getCompletedStages(stages: Stage[] = STAGES, now: Date = new Date()): Stage[] {
  return stages
    .filter((s) => resolveStageStatus(s, now) === "completed")
    .sort((a, b) => new Date(b.fullDate).getTime() - new Date(a.fullDate).getTime());
}

